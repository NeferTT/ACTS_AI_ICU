AUDIT_FIELDS = [
    "timestamp", "case_id", "case_type", "model", "prompt_version",
    "in_scope", "trajectory", "decision", "reviewer",
    "total_statements", "traceability_pct", "unsupported_count",
    "missing_data_count", "contradictions_count",
    "percent_changed", "review_seconds",
    "edit_unknown_tags", "edit_absence_conflicts",
    "edit_cross_section_conflicts", "edit_untagged_additions",
    "flags_acknowledged", "reviewer_comment",
]


# --------------------------------------------------------------------------
# Post-edit consistency check
#
# The AI draft is validated for traceability before the physician sees it.
# These functions re-validate the note AFTER physician editing, because a
# physician edit can introduce a statement that is untraceable, that asserts
# something the source data marks as absent, or that contradicts another
# section. The physician remains free to add clinical knowledge the structured
# data does not contain - the system flags, it does not block.
# --------------------------------------------------------------------------

import re  # noqa: E402

TAG_PATTERN = re.compile(r"`\[([^\]]*)\]`")

ABSENCE_MARKERS = (
    "not documented", "undocumented", "not available", "not recorded",
    "not provided", "missing", "no data", "unavailable", "not performed",
    "not stated", "cannot be confirmed", "cannot be determined",
)


_NEGATION_START = re.compile(r"^\s*(?:\d+\.\s*)?no\b", re.IGNORECASE)

_ABSENCE_CONTEXT = (
    "document", "available", "record", "provid", "report", "perform",
    "result", "assess", "data",
)


def _has_absence_marker(text):
    """
    True when a statement asserts that something is absent.

    Two phrasings must both be recognised:
      "stress ulcer prophylaxis is not documented"      -> explicit marker
      "no arterial blood gas results were available"    -> leading negation
    Missing the second form causes correct absence statements to be flagged as
    if they asserted content.
    """
    low = text.lower()
    if any(marker in low for marker in ABSENCE_MARKERS):
        return True
    if _NEGATION_START.match(low) and any(c in low for c in _ABSENCE_CONTEXT):
        return True
    return False


def parse_tagged_lines(note_text):
    """
    Walk the edited markdown note and return
    [(section_title, line_text, [source_ids]), ...] for every bullet line.
    """
    results = []
    section = "(before first section)"
    for raw in note_text.splitlines():
        line = raw.strip()
        if line.startswith("###"):
            section = line.lstrip("#").strip()
            continue
        if not line.startswith("- "):
            continue
        body = line[2:].strip()
        tags = []
        match = TAG_PATTERN.search(body)
        if match:
            tags = [t.strip() for t in match.group(1).split(",") if t.strip()]
            body = TAG_PATTERN.sub("", body).strip()
        results.append((section, body, tags))
    return results


def collect_absent_source_ids(case):
    """
    Source ids whose data element is explicitly marked as absent in the input
    (available=false or documented=false).
    """
    absent = set()

    def walk(node):
        if isinstance(node, dict):
            sid = node.get("source_id")
            if isinstance(sid, str):
                if node.get("available") is False or node.get("documented") is False:
                    absent.add(sid)
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for item in node:
                walk(item)

    walk(case)
    return absent


def strip_source_tags(note_text):
    """
    Remove evidence tags to produce the clean clinical version of the note.

    Both versions matter: the tagged version is the verification artefact
    (it is what makes traceability auditable), while the clean version is what
    would actually be filed in the record.
    """
    cleaned = []
    for line in note_text.splitlines():
        line = TAG_PATTERN.sub("", line)
        line = re.sub(r"\s+$", "", line)
        line = re.sub(r"^(\s*)-\s+-\s+", r"\1- ", line)  # tidy double bullets
        cleaned.append(line)
    return "\n".join(cleaned)


def _is_absence_section(section_title):
    """
    Sections whose purpose is to enumerate what is absent. A statement here is
    an absence statement by virtue of where it sits, even if the sentence
    itself contains no absence wording. Without this, prompt v1.3 (which
    correctly instructs the model to cite the absent element's source_id in
    the Missing Data list) causes every such line to be flagged.
    """
    return section_title.strip().lower().startswith("missing data")


def check_edited_note(note_text, case):
    """
    Re-validate a physician-edited note.

    Returns a dict of findings:
      unknown_tags        - cites a source_id that does not exist in the input
      absence_conflicts   - asserts content under a source marked absent
      cross_section       - same source cited as both present and absent
      untagged_additions  - bullet with no source tag at all
    """
    valid_ids = collect_source_ids(case) | {"NO_DATA"}
    absent_ids = collect_absent_source_ids(case)

    lines = parse_tagged_lines(note_text)

    unknown_tags, absence_conflicts, untagged = [], [], []
    by_tag = {}

    for section, body, tags in lines:
        if not body:
            continue
        if not tags:
            untagged.append((section, body))
            continue
        bad = [t for t in tags if t not in valid_ids]
        if bad:
            unknown_tags.append((section, body, bad))

        states_absence = _is_absence_section(section) or _has_absence_marker(body)

        for tag in tags:
            if tag == "NO_DATA":
                continue
            by_tag.setdefault(tag, []).append((section, body, states_absence))
            if tag in absent_ids and not states_absence:
                absence_conflicts.append((section, body, tag))

    cross_section = []
    for tag, entries in by_tag.items():
        if len(entries) < 2:
            continue
        absent_lines = [(s, b) for s, b, a in entries if a]
        present_lines = [(s, b) for s, b, a in entries if not a]
        if absent_lines and present_lines:
            cross_section.append((tag, present_lines, absent_lines))

    return {
        "unknown_tags": unknown_tags,
        "absence_conflicts": absence_conflicts,
        "cross_section": cross_section,
        "untagged_additions": untagged,
        "total_flags": (
            len(unknown_tags) + len(absence_conflicts)
            + len(cross_section) + len(untagged)
        ),
    }


def _write_row(path, row):
    exists = os.path.isfile(path)
    with open(path, "a", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=AUDIT_FIELDS)
        if not exists:
            writer.writeheader()
        writer.writerow({k: row.get(k, "") for k in AUDIT_FIELDS})


def append_audit(row, path=AUDIT_LOG):
    """
    Append one review event to the CSV audit trail.

    An audit trail must never silently lose an entry. If the primary file is
    locked (commonly because it is open in Excel on Windows), the entry is
    written to a timestamped fallback file instead of failing.

    Returns (path_written, note) so the UI can tell the reviewer what happened.
    """
    try:
        _write_row(path, row)
        return path, None
    except PermissionError:
        stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        base, ext = os.path.splitext(path)
        fallback = f"{base}_{stamp}{ext}"
        try:
            _write_row(fallback, row)
            return fallback, (
                f"'{path}' was locked (it is probably open in Excel). "
                f"The entry was saved to '{fallback}' instead — close Excel and "
                "merge the files, or keep them as separate session logs."
            )
        except Exception as exc:  # noqa: BLE001
            return None, f"Audit entry could NOT be saved: {exc}"
    except Exception as exc:  # noqa: BLE001
        return None, f"Audit entry could NOT be saved: {exc}"


def now_iso():
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")
