"""
ACTS-AI MVP — core logic
Case loading, input sanitisation, traceability validation, note assembly,
diff metrics, and audit logging. Kept separate from the UI so it can be
unit-tested and reused by an n8n / API deployment.
"""

import csv
import difflib
import json
import os
from datetime import datetime

CASES_DIR = "cases"
AUDIT_LOG = "audit_log.csv"

# Keys that exist only to document the test design. They must be removed
# before the case is sent to the model, otherwise the model can "cheat" by
# reading the planted answers.
TEST_ONLY_KEYS = {
    "expected_behavior_for_testing",
    "intentional_data_gaps_for_testing",
    "planted_gaps",
    "planted_safety_signal",
    "planted_contradictions",
    "must_not_do",
}


# --------------------------------------------------------------------------
# Case loading and sanitisation
# --------------------------------------------------------------------------

def list_cases(cases_dir=CASES_DIR):
    """Return sorted list of case filenames available on disk."""
    if not os.path.isdir(cases_dir):
        return []
    return sorted(f for f in os.listdir(cases_dir) if f.endswith(".json"))


def load_case(filename, cases_dir=CASES_DIR):
    with open(os.path.join(cases_dir, filename), "r", encoding="utf-8") as fh:
        return json.load(fh)


def strip_test_metadata(obj):
    """Recursively remove evaluation-design keys before sending to the model."""
    if isinstance(obj, dict):
        return {
            k: strip_test_metadata(v)
            for k, v in obj.items()
            if k not in TEST_ONLY_KEYS
        }
    if isinstance(obj, list):
        return [strip_test_metadata(v) for v in obj]
    return obj


_INVISIBLE = "\u200b\u200c\u200d\ufeff\u00a0\u2060"


def _is_blank(value):
    """
    True when a statement carries no readable text.

    Ordinary strip() leaves zero-width and non-breaking characters in place, so
    a statement containing only those looks non-empty in code but renders as a
    bare tag with nothing before it.
    """
    if not isinstance(value, str):
        return not value
    return not value.strip().strip(_INVISIBLE).strip()


def collect_source_ids(obj, found=None):
    """Recursively collect every source_id value present in the case data."""
    if found is None:
        found = set()
    if isinstance(obj, dict):
        for key, value in obj.items():
            if key == "source_id" and isinstance(value, str):
                found.add(value)
            else:
                collect_source_ids(value, found)
    elif isinstance(obj, list):
        for item in obj:
            collect_source_ids(item, found)
    return found


def patient_header(case):
    """
    Build the patient identity line directly from the input JSON.
    Deliberately NOT generated by the model - zero hallucination risk on
    the most identity-critical line of the note.
    """
    demo = case.get("demographics", {}) or {}
    adm = case.get("admission_info", {}) or {}
    meta = case.get("case_metadata", {}) or {}
    age = demo.get("age", "?")
    sex = demo.get("sex", "?")
    weight = demo.get("weight_kg")
    weight_txt = f", {weight} kg" if weight else ""
    day = meta.get("icu_day", "?")
    date = meta.get("note_date", "")
    dx = adm.get("admission_diagnosis", "not documented")
    intub = adm.get("intubation_date")
    intub_txt = f"; intubated {intub}" if intub else ""
    return (
        f"**Daily ICU Progress Note — ICU Day {day}**\n\n"
        f"**Date:** {date} | **Patient:** {age}{sex}{weight_txt}\n\n"
        f"**Admission:** {adm.get('admission_date', 'n/a')} — {dx}{intub_txt}\n"
    )


# --------------------------------------------------------------------------
# Traceability validation (the automated hallucination check)
# --------------------------------------------------------------------------

def validate_traceability(ai_output, case):
    """
    Check every source_id cited by the model against the source_ids that
    actually exist in the input case.

    Returns a dict of metrics used both for the live UI warning and for the
    Phase 6 evaluation table.
    """
    valid_ids = collect_source_ids(case)
    valid_ids.add("NO_DATA")  # sentinel permitted by prompt v1.2

    total_statements = 0
    untagged = []          # statements with no source_ids at all
    invalid_refs = []      # statements citing an id not present in the input
    empty = []             # statements the model emitted with no text at all

    for section in ai_output.get("note_sections", []) or []:
        for st in section.get("statements", []) or []:
            total_statements += 1
            raw = st.get("text") or ""
            text = raw.strip() if isinstance(raw, str) else ""
            ids = st.get("source_ids") or []
            if _is_blank(raw):
                empty.append(section.get("title", "?"))
                continue
            if not ids:
                untagged.append((section.get("title", "?"), text))
                continue
            bad = [i for i in ids if i not in valid_ids]
            if bad:
                invalid_refs.append((section.get("title", "?"), text, bad))

    problems = len(untagged) + len(invalid_refs) + len(empty)
    traceable = total_statements - problems
    pct = round(100 * traceable / total_statements, 1) if total_statements else 0.0

    return {
        "total_statements": total_statements,
        "fully_traceable": traceable,
        "traceability_pct": pct,
        "untagged": untagged,
        "invalid_refs": invalid_refs,
        "empty_statements": empty,
        "unsupported_count": problems,
    }


# --------------------------------------------------------------------------
# Note assembly (JSON -> editable markdown)
# --------------------------------------------------------------------------

def assemble_note(ai_output, case, include_tags=True):
    """Render the structured AI output as an editable markdown note."""
    if not ai_output.get("in_scope", False):
        return (
            "## OUT OF SCOPE — NO NOTE GENERATED\n\n"
            f"**Reason:** {ai_output.get('scope_reason', 'not stated')}\n\n"
            "This patient falls outside the validated pilot population "
            "(adult ICU patient receiving invasive mechanical ventilation). "
            "No draft documentation has been produced."
        )

    parts = [patient_header(case), ""]

    for section in ai_output.get("note_sections", []) or []:
        title = section.get("title", "Untitled")
        statements = section.get("statements", []) or []
        parts.append(f"### {title}")
        if not statements:
            parts.append("_No data provided for this system._")
        for st in statements:
            raw = st.get("text") or ""
            if _is_blank(raw):
                continue  # malformed empty statement; reported in the quality panel
            text = raw.strip()
            if include_tags:
                ids = ", ".join(st.get("source_ids") or []) or "UNTAGGED"
                parts.append(f"- {text} `[{ids}]`")
            else:
                parts.append(f"- {text}")
        parts.append("")

    contradictions = ai_output.get("contradictions", []) or []
    if contradictions:
        parts.append("### Contradictions Flagged for Verification")
        for c in contradictions:
            ids = ", ".join(c.get("source_ids") or [])
            parts.append(f"- {c.get('description', '')} `[{ids}]`")
        parts.append("")

    parts.append(f"**Trajectory:** {ai_output.get('trajectory', 'not stated')}")
    parts.append("")
    parts.append(f"_{ai_output.get('draft_disclaimer', '')}_")
    return "\n".join(parts)


# --------------------------------------------------------------------------
# Diff metrics
# --------------------------------------------------------------------------

def diff_metrics(draft, final):
    """
    Word-level comparison between AI draft and physician-approved note.
    Returns percentage of the draft changed plus word counts.
    """
    draft_words = draft.split()
    final_words = final.split()
    matcher = difflib.SequenceMatcher(None, draft_words, final_words)
    matched = sum(block.size for block in matcher.get_matching_blocks())
    changed_pct = (
        round(100 * (1 - matched / len(draft_words)), 1) if draft_words else 0.0
    )
    return {
        "draft_words": len(draft_words),
        "final_words": len(final_words),
        "unchanged_words": matched,
        "percent_changed": changed_pct,
        "similarity_ratio": round(matcher.ratio() * 100, 1),
    }


def render_diff_html(draft, final):
    """Word-level inline diff as HTML for display in the review screen."""
    matcher = difflib.SequenceMatcher(None, draft.split(), final.split())
    out = []
    for tag, i1, i2, j1, j2 in matcher.get_opcodes():
        old = " ".join(draft.split()[i1:i2])
        new = " ".join(final.split()[j1:j2])
        if tag == "equal":
            out.append(old)
        elif tag == "delete":
            out.append(f"<span style='background:#ffd6d6;text-decoration:line-through'>{old}</span>")
        elif tag == "insert":
            out.append(f"<span style='background:#d6f5d6'>{new}</span>")
        elif tag == "replace":
            out.append(f"<span style='background:#ffd6d6;text-decoration:line-through'>{old}</span>")
            out.append(f"<span style='background:#d6f5d6'>{new}</span>")
    return " ".join(out)


